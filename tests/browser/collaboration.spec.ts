test("permanent task links recover older filtered records and context downloads are usable", async ({ page }) => {
  const taskReads: string[] = [];
  page.on("request", request => { if (new URL(request.url()).pathname === "/_api/project/task") taskReads.push(request.url()); });
  await page.goto(`${projectPath}?tab=tasks&status=open#tsk_demo_001`);
  await ready(page, projectTitle);
  const linked = page.locator("#tsk_demo_001");
  await expect(linked).toBeVisible(); await expect(linked.locator("details")).toHaveAttribute("open", "");
  await expect(linked.getByRole("heading", { name: "Recorded outcome" })).toBeVisible();
  await expect(page.getByRole("navigation", { name: "Task status" }).getByRole("link", { name: "Open", exact: true })).toHaveAttribute("aria-current", "page");
  expect(taskReads.some(url => new URL(url).searchParams.get("id") === "tsk_demo_001")).toBe(true);
  await noOverflow(page);
  const downloading = page.waitForEvent("download");
  await page.getByRole("link", { name: "Project context", exact: true }).click();
  const download = await downloading;
  expect(download.suggestedFilename()).toBe("assembly-project-prj_demo_research.json");
  const context = JSON.parse(await readFile((await download.path())!, "utf8"));
  expect(context.project.id).toBe("prj_demo_research");
  expect(context.tasks.items).toHaveLength(20);
  expect(context.research.items).toHaveLength(3);
  expect(context.discussions.items).toHaveLength(1);
  expect(JSON.stringify(context)).not.toMatch(/api_key_hash|apiKey|Authorization/);
  await page.context().grantPermissions(["clipboard-read", "clipboard-write"]);
  await page.getByRole("button", { name: "Copy link", exact: true }).click();
  await expect(page.getByRole("button", { name: "Link copied", exact: true })).toBeVisible();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(`http://localhost:4173${projectPath}`);
});

